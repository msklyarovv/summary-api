import { ObjectType, Field, Int } from '@nestjs/graphql';

/**
 * Статистика просмотров профиля.
 *
 * Текущая реализация: in-memory счётчик.
 * Ограничение: сбрасывается при перезапуске и не масштабируется горизонтально.
 *
 * Точка роста (для обсуждения на интервью):
 * Подключить Redis через ICacheService — счётчик станет персистентным
 * и будет корректно работать при нескольких репликах приложения.
 * Дополнительно: аналитика по времени суток, уникальные посетители (по IP-хэшу).
 */
@ObjectType()
export class ProfileStats {
  @Field(() => Int, { description: 'Просмотров с последнего запуска сервера' })
  viewCount: number;

  @Field(() => Date, { nullable: true, description: 'Время последнего просмотра' })
  lastViewedAt: Date | null;
}
